import json, random, os

random.seed(20261125)

def build(pid, name, price, cats, total, generic_pos, generic_neg, openers, closers):
    """cats: list of (tag, ratio, phrases, rating_range)"""
    reviews = []
    pool = []
    for tag, ratio, phrases, rr in cats:
        n = max(1, round(total * ratio))
        for i in range(n):
            pool.append((tag, phrases[i % len(phrases)], rr))
    random.shuffle(pool)
    neg_n = len(pool)
    for i in range(total):
        parts = []
        if random.random() < 0.55:
            parts.append(random.choice(openers))
        if i < neg_n:
            tag, phrase, rr = pool[i]
            if random.random() < 0.6:
                parts.append(random.choice(generic_pos))
            pre = random.choice(["", "", "다 좋은데", "단점을 꼽자면", "솔직히", "아쉬운 점은", "근데", "하나 걸리는 건"])
            parts.append((pre + " " + phrase) if pre else phrase)
            rating = random.randint(*rr)
            truth = [tag]
        else:
            k = random.choice([1, 1, 2])
            parts.extend(random.sample(generic_pos, k))
            if random.random() < 0.18:
                parts.append(random.choice(generic_neg))
            rating = random.choice([5, 5, 5, 4, 4, 5])
            truth = []
        if random.random() < 0.45:
            parts.append(random.choice(closers))
        reviews.append({"rating": rating, "text": " ".join(parts), "_truth": truth})
    random.shuffle(reviews)
    for i, r in enumerate(reviews):
        r["id"] = f"{pid}-{i+1:03d}"
    avg = round(sum(r["rating"] for r in reviews) / len(reviews), 1)
    return {"id": pid, "name": name, "price": price, "avg": avg, "count": len(reviews), "reviews": reviews}

